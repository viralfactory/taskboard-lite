update tasks set cat_l1 = '업무개선/기타'
 where cat_l1 in ('업무개선/역량', '개선활동', '역량개발');

update profiles set last_cat_l1 = '업무개선/기타'
 where last_cat_l1 in ('업무개선/역량', '개선활동', '역량개발');

